"""REAL Blender smoke renders of every studio scene (opt in: ``pytest --runslow tests/blender_kits``).

Each scene renders 2 frames (first + last) at a tiny preview resolution in both aspects on the self-made CC0 test car
(generated by make_testcar.py) with a red ``paint`` override: the build must not raise, frames must decode, and the
red car must be in the last frame.
Needs Blender >= 4.2 (HYPE_BLENDER or the usual locations; skipped otherwise). Dev-PC locks: devguard.py.
"""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import kitcheck as kc  # noqa: E402

kc.blender_dev_env()
from devguard import dev_lock, min_free_gb  # noqa: E402

from showreel_core.blender import locate as loc  # noqa: E402
from showreel_core.blender import runner  # noqa: E402

pytestmark = pytest.mark.slow
RES = {"16:9": (256, 144), "9:16": (144, 256)}


@pytest.fixture(scope="module")
def blender():
    found = loc.locate()
    if not found.ok:
        pytest.skip(found.message)
    return found


@pytest.fixture(scope="module")
def testcar(tmp_path_factory, blender):
    d = tmp_path_factory.mktemp("car")
    script = Path(__file__).parent / "make_testcar.py"
    with dev_lock("hype-kit-tests"):
        subprocess.run([str(blender.path), "-b", "--factory-startup", "--python-exit-code", "1", "-P", str(script),
                        "--", str(d)], check=True, capture_output=True, timeout=300)
    car = d / "testcar.glb"
    assert car.is_file()
    return {"car": {"kind": "model", "path": str(car)}}


def _pixels(im) -> list:
    flat = getattr(im, "get_flattened_data", None)   # Pillow >= 12.1 (getdata is deprecated)
    return list(flat() if flat else im.getdata())


def _render(blender, tmp_path, scene: str, aspect: str, assets: dict, product: str, params: dict | None = None,
            dur: float = 2.0):
    job = runner.make_job(kc.KITS / f"{scene}.py", tmp_path / scene.replace("/", "_") / aspect.replace(":", "x"),
                          dur=dur, fps=30, res=RES[aspect], params=params or {}, tier="preview",
                          frames=[1, int(dur * 30)], assets=assets, product=product)
    r = runner.run_job(job, blender, lock=lambda: dev_lock("hype-kit-tests"), min_free_gb=min_free_gb(),
                       timeout_s=300)
    assert r.ok, (r.error, r.traceback[-2000:] if r.traceback else "", r.log)
    return [runner.frame_path(job, f) for f in (1, int(dur * 30))]


@pytest.mark.parametrize("aspect", ["16:9", "9:16"])
@pytest.mark.parametrize("scene", ["studio/product_hero", "studio/product_float"])
def test_studio_scene_renders_a_model(blender, tmp_path, testcar, scene, aspect):
    files = _render(blender, tmp_path, scene, aspect, testcar, "car", {"model": "car", "paint": "#b5121b"})
    from PIL import Image

    last = Image.open(files[-1]).convert("RGB")
    px = _pixels(last)
    red = sum(1 for r, g, b in px if r > 70 and r > 2 * g and r > 2 * b)
    assert red > len(px) * 0.01, "the red-painted car is not in the frame"
