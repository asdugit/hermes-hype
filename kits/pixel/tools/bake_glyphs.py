"""Bake the pixel kit's bitmap fonts (dev-time tool; the kit only ships the generated table).

Each OFL font is rasterised with Pillow at 4x its native pixel size and point-sampled at every
cell centre, which yields exact 1-bit glyphs (no anti-alias greys, no filled 'w'/'m' stems).
Output: ``kits/pixel/core/glyphs.js`` (ES module, plain data).

    python kits/pixel/tools/bake_glyphs.py

The generated glyph sets are renamed (``mono``/``caps``/``tiny``) because Press Start 2P's
licence reserves its name for unmodified versions; the OFL texts ship in ``kits/pixel/fonts``.
"""
from __future__ import annotations

import json
from pathlib import Path

from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont

KIT = Path(__file__).resolve().parent.parent
SS = 4  # supersampling factor
EXTRA = "★✓✗♥→←↑↓▼▲►◄…×·•↪░▒▓█─│┌┐└┘"

FONTS = {
    # name: (file, native px size, line height, source font credit)
    "mono": ("DepartureMono-Regular.otf", 11, 14, "Departure Mono (Helena Zhang), OFL-1.1"),
    "caps": ("PressStart2P-Regular.ttf", 8, 12, "Press Start 2P (The Press Start 2P Project Authors), OFL-1.1"),
    "tiny": ("Silkscreen-Regular.ttf", 8, 10, "Silkscreen (Jason Kottke), OFL-1.1"),
}


def bake(file: str, size: int, lh: int) -> dict:
    """Return {asc, lh, glyphs: {char: [adv, x0, y0, w, h, rowbits...]}} for one font."""
    path = KIT / "fonts" / file
    cmap = TTFont(path).getBestCmap()
    font = ImageFont.truetype(str(path), size * SS)
    asc, desc = font.getmetrics()
    asc_px = round(asc / SS)
    chars = [chr(c) for c in range(32, 127)] + [c for c in EXTRA if ord(c) in cmap]
    glyphs: dict[str, list[int]] = {}
    pad = 3
    for ch in chars:
        adv = round(font.getlength(ch) / SS)
        cw, chh = adv + pad * 2, asc_px + round(desc / SS) + pad * 2
        im = Image.new("L", (cw * SS, chh * SS), 0)
        ImageDraw.Draw(im).text((pad * SS, (pad + asc_px) * SS), ch, font=font, fill=255, anchor="ls")
        px = im.load()
        cells = [[px[i * SS + SS // 2, j * SS + SS // 2] >= 128 for i in range(cw)] for j in range(chh)]
        ys = [j for j in range(chh) if any(cells[j])]
        xs = [i for i in range(cw) if any(cells[j][i] for j in range(chh))]
        if not ys:
            glyphs[ch] = [adv, 0, 0, 0, 0]
            continue
        x0, x1, y0, y1 = xs[0], xs[-1], ys[0], ys[-1]
        rows = []
        for j in range(y0, y1 + 1):
            bits = 0
            for i in range(x0, x1 + 1):
                if cells[j][i]:
                    bits |= 1 << (i - x0)
            rows.append(bits)
        # x/y relative to the pen position on the baseline
        glyphs[ch] = [adv, x0 - pad, y0 - pad - asc_px, x1 - x0 + 1, y1 - y0 + 1, *rows]
    return {"size": size, "asc": asc_px, "lh": lh, "glyphs": glyphs}


def main() -> None:
    out = {}
    credits = []
    for name, (file, size, lh, credit) in FONTS.items():
        out[name] = bake(file, size, lh)
        credits.append(f"//   {name}: {credit}")
    js = ("// GENERATED by kits/pixel/tools/bake_glyphs.py - do not edit.\n"
          "// 1-bit bitmap glyph tables rasterised from OFL-1.1 fonts (licences in ../fonts/):\n"
          + "\n".join(credits) + "\n"
          "// glyph = [advance, x0, y0 (from baseline, negative = up), w, h, ...row bitmasks (bit i = column x0+i)]\n"
          "export const GLYPHS = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n")
    dst = KIT / "core" / "glyphs.js"
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text(js, encoding="utf-8")
    for name, f in out.items():
        print(name, "asc", f["asc"], "glyphs", len(f["glyphs"]))
        for ch in "wmAg":
            g = f["glyphs"][ch]
            print(f" {ch!r} adv={g[0]} x0={g[1]} y0={g[2]} w={g[3]} h={g[4]}")
            for r in g[5:]:
                print("   " + "".join("#" if r >> i & 1 else "." for i in range(g[3])))
    print("wrote", dst, dst.stat().st_size, "bytes")


if __name__ == "__main__":
    main()
