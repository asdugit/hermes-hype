export const MONSTERS = M;
export const MONSTER_IDS = Object.keys(M);
const CACHE = new Map();
/** Monster sprite (frame 0/1), facing left. `tint` overrides row-map chars (e.g. {a: 'coral'}). Unknown id -> goo. */
export function monster(id, frame = 0, { tint = null } = {}) {
  const key = `${id}|${frame & 1}|${tint ? JSON.stringify(tint) : ''}`;
  if (CACHE.has(key)) return CACHE.get(key);
  const m = M[id] || M.goo, map = tint ? { ...m.map, ...tint } : m.map;
  const s = Sprite.rows(m.frames[frame & 1], map);
  CACHE.set(key, s);
  return s;
}
